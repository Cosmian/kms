use std::collections::HashMap;

use base64::{
    Engine as _,
    prelude::{BASE64_STANDARD, BASE64_URL_SAFE_NO_PAD},
};
use cosmian_kms_crypto::crypto::KmsRng;
use http::{HeaderMap, HeaderValue, StatusCode, header::ACCEPT};
use serde::{Deserialize, Serialize};
use url::Url;
use zeroize::Zeroizing;

use super::{HttpClientError, error::result::HttpClientResult};

/// Entropy of the PKCE code verifier: 32 bytes encode to 43 base64url characters, the RFC 7636 §4.1
/// minimum length (and the recommended 256 bits).
const PKCE_VERIFIER_BYTES: usize = 32;
/// Entropy of the CSRF `state` token (RFC 6749 §10.12).
const CSRF_TOKEN_BYTES: usize = 32;

/// `len` random bytes from [`KmsRng`], base64url-encoded without padding.
///
/// The result is a secret (PKCE verifier, CSRF token): it is wiped on drop.
fn random_token(len: usize) -> HttpClientResult<Zeroizing<String>> {
    let bytes = KmsRng::new()
        .random_vec(len)
        .map_err(|e| HttpClientError::Default(format!("cannot generate random bytes: {e}")))?;
    Ok(Zeroizing::new(BASE64_URL_SAFE_NO_PAD.encode(&*bytes)))
}

/// PKCE `S256` code challenge (RFC 7636 §4.2): `BASE64URL(SHA256(verifier))`, no padding.
fn pkce_challenge(verifier: &str) -> HttpClientResult<String> {
    let digest = openssl::hash::hash(openssl::hash::MessageDigest::sha256(), verifier.as_bytes())?;
    Ok(BASE64_URL_SAFE_NO_PAD.encode(&*digest))
}

/// Constant-time equality of two secret strings.
fn constant_time_eq(a: &str, b: &str) -> bool {
    // `memcmp::eq` requires equal lengths; the length of a random token is not secret.
    a.len() == b.len() && openssl::memcmp::eq(a.as_bytes(), b.as_bytes())
}

/// Build the authorization request URL (RFC 6749 §4.1.1 with the PKCE parameters of RFC 7636 §4.3).
///
/// Query parameters already present in the configured `authorize_url` are preserved.
fn authorization_url(
    login_config: &Oauth2LoginConfig,
    redirect_url: &Url,
    state: &str,
    code_challenge: &str,
) -> HttpClientResult<Url> {
    let mut url = Url::parse(&login_config.authorize_url)?;
    {
        let mut query = url.query_pairs_mut();
        query
            .append_pair("response_type", "code")
            .append_pair("client_id", &login_config.client_id)
            .append_pair("redirect_uri", redirect_url.as_str())
            .append_pair("state", state)
            .append_pair("code_challenge", code_challenge)
            .append_pair("code_challenge_method", "S256");
        if !login_config.scopes.is_empty() {
            query.append_pair("scope", &login_config.scopes.join(" "));
        }
    }
    Ok(url)
}

#[derive(Serialize, Deserialize, Eq, PartialEq, Clone)]
pub struct Oauth2LoginConfig {
    /// The client ID of your application.
    pub client_id: String,
    /// The client secret of your application.
    pub client_secret: String,
    /// The authorization URL of the provider.
    /// For example, for Google it is `https://accounts.google.com/o/oauth2/v2/auth`.
    pub authorize_url: String,
    /// The token URL of the provider.
    /// For example, for Google it is `https://oauth2.googleapis.com/token`.
    pub token_url: String,
    /// The scopes to request.
    /// For example, for Google it is `["openid", "email"]`.
    pub scopes: Vec<String>,
    /// Refresh token saved by `ckms login oauth` when the identity provider returns one (request the
    /// `offline_access` scope); `ckms login oauth --refresh` exchanges it without a browser.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub refresh_token: Option<String>,
}

impl std::fmt::Debug for Oauth2LoginConfig {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Oauth2LoginConfig")
            .field("client_id", &self.client_id)
            .field("client_secret", &"<redacted>")
            .field("authorize_url", &self.authorize_url)
            .field("token_url", &self.token_url)
            .field("scopes", &self.scopes)
            .field(
                "refresh_token",
                &self.refresh_token.as_ref().map(|_| "<redacted>"),
            )
            .finish()
    }
}

/// This struct holds the state of the login process.
/// It is used to generate the authorization URL and to store the PKCE verifier
/// and the CSRF token.
///
/// The user should browse to the authorization URL and follow the instructions
/// to authenticate. The Url can be recovered by accessing to field `auth_url`.
///
/// The CSRF token is used to verify that the authorization code received on the
/// redirect URL matches the one generated by the client.
/// The PKCE verifier is used to verify that the authorization code received on
/// the redirect URL matches the one generated by the client.
/// See [RFC 7636](https://tools.ietf.org/html/rfc7636) for more details.
/// See [PKCE](https://oauth.net/2/pkce/) for more details.
/// See [CSRF](https://en.wikipedia.org/wiki/Cross-site_request_forgery) for more details.
/// See [OAuth2](https://oauth.net/2/) for more details.
/// See [OAuth2 RFC](https://tools.ietf.org/html/rfc6749) for more details.
pub struct LoginState {
    login_config: Oauth2LoginConfig,
    redirect_url: Url,
    pub auth_url: Url,
    pkce_verifier: Zeroizing<String>,
    csrf_token: Zeroizing<String>,
}

/// This function initializes the login process.
/// It returns a `LoginState` that holds the state of the login process.
///
/// The process should be completed by instructing the user to browse to the
/// authorization URL and follow the instructions to authenticate
/// and immediately after calling `finalize()` with the returned `LoginState`.
///
/// The Url can be recovered by accessing `auth_url` on the returned
/// `LoginState` struct.
impl TryFrom<Oauth2LoginConfig> for LoginState {
    type Error = HttpClientError;

    fn try_from(login_config: Oauth2LoginConfig) -> Result<Self, Self::Error> {
        // if the port is specified in the environment variable, use it
        let port = if let Ok(port_s) = std::env::var("OAUTH2_REDIRECT_URL_PORT") {
            port_s.parse::<u16>().map_err(|e| {
                HttpClientError::Default(format!("Invalid OAUTH2_REDIRECT_URL_PORT: {e:?}"))
            })?
        } else {
            17_899_u16
        };
        Self::build(login_config, port)
    }
}

impl LoginState {
    /// Build a `LoginState` using the given explicit redirect port.
    ///
    /// This is the internal constructor shared by `TryFrom` and the
    /// test-only `try_from_with_port` helper.
    fn build(login_config: Oauth2LoginConfig, port: u16) -> HttpClientResult<Self> {
        let mut redirect_url = Url::parse("http://localhost:17899/authorization")?;
        redirect_url.set_port(Some(port)).map_err(|()| {
            HttpClientError::Default(format!("Failed to set redirect URL port to {port}"))
        })?;

        // Validate the token endpoint now so a bad configuration fails before the browser opens.
        Url::parse(&login_config.token_url)?;

        // PKCE (RFC 7636): random verifier, S256 challenge.
        let pkce_verifier = random_token(PKCE_VERIFIER_BYTES)?;
        let pkce_challenge = pkce_challenge(&pkce_verifier)?;
        // CSRF token, echoed back by the IdP in the `state` parameter.
        let csrf_token = random_token(CSRF_TOKEN_BYTES)?;

        // This is the URL you should redirect the user to,
        // in order to trigger the authorization process.
        let auth_url =
            authorization_url(&login_config, &redirect_url, &csrf_token, &pkce_challenge)?;

        Ok(Self {
            login_config,
            redirect_url,
            auth_url,
            pkce_verifier,
            csrf_token,
        })
    }

    /// Construct a `LoginState` bound to an explicit `port`, bypassing the
    /// `OAUTH2_REDIRECT_URL_PORT` environment variable.
    ///
    /// Only available in test builds.  Lets each test bind its own port so
    /// parallel tests never collide on the same socket.
    #[cfg(test)]
    pub(crate) fn try_from_with_port(
        login_config: Oauth2LoginConfig,
        port: u16,
    ) -> HttpClientResult<Self> {
        Self::build(login_config, port)
    }

    /// This function finalizes the login process.
    /// It returns the identity provider tokens.
    ///
    /// This function should be called immediately after the user has been
    /// instructed to browse to the authorization URL. It starts a server on
    /// localhost:17899 and waits for the authorization code to be received
    /// from the browser window. Once the code is received, the server is closed
    /// and the code is returned.
    ///
    /// # Errors
    ///
    /// This function can return a `HttpClientError` in the following cases:
    ///
    /// * The authorization code, state, or other parameters are not received
    ///   from the redirect URL.
    /// * The received state does not match the CSRF token.
    /// * The authorization code is not received on authentication.
    /// * The code received on authentication does not match the CSRF token.
    /// * The access token cannot be requested from the Identity Provider.
    /// * The token exchange request fails.
    /// * The token exchange response cannot be parsed.
    pub async fn finalize(&self) -> HttpClientResult<OAuthTokens> {
        // recover the authorization code, state and other parameters from the redirect
        // URL.  Use the port that was actually embedded in the redirect URL at
        // construction time (respects OAUTH2_REDIRECT_URL_PORT).
        let port = self.redirect_url.port_or_known_default().unwrap_or(17_899);
        let (auth_parameters, server) = Self::receive_authorization_parameters(port).await?;
        // Stop accepting callbacks; dropping the listener frees the port.
        server.abort();

        // Once the user has been redirected to the redirect URL, you'll have access to
        // the authorization code. For security reasons, your code should verify
        // that the `state` parameter returned by the server matches
        // `csrf_state`.
        let received_state = auth_parameters.get("state").ok_or_else(|| {
            HttpClientError::Default("state not received on authentication".to_owned())
        })?;
        if !constant_time_eq(received_state, &self.csrf_token) {
            return Err(HttpClientError::Default(
                "state received on authentication does not match".to_owned(),
            ));
        }

        // extract the authorization code
        let authorization_code = auth_parameters.get("code").ok_or_else(|| {
            HttpClientError::Default("code not received on authentication".to_owned())
        })?;

        request_token(
            &self.login_config,
            &self.redirect_url,
            &self.pkce_verifier,
            authorization_code,
        )
        .await
    }

    /// This function starts the server on the given `port` and waits for the
    /// authorization code to be received from the browser window. Once the
    /// code is received, the server task handle is returned alongside the
    /// parameters so the caller can stop the server and free the port.
    ///
    /// The port must match the one embedded in the redirect URL that was sent
    /// to the Identity Provider during the authorization request.
    async fn receive_authorization_parameters(
        port: u16,
    ) -> HttpClientResult<(HashMap<String, String>, tokio::task::JoinHandle<()>)> {
        // Bind first so a port-in-use error is reported to the caller, not to a spawned task.
        let listener = tokio::net::TcpListener::bind(("127.0.0.1", port))
            .await
            .map_err(|e| {
                HttpClientError::Default(format!(
                    "cannot bind port {port} for OAuth2 callback: {e}"
                ))
            })?;

        let (tx, mut rx) = tokio::sync::mpsc::unbounded_channel::<HashMap<String, String>>();
        let server = tokio::spawn(async move {
            while let Ok((stream, _)) = listener.accept().await {
                let tx = tx.clone();
                tokio::spawn(async move {
                    let service = hyper::service::service_fn(move |req| {
                        let response = authorization_response(&req, &tx);
                        async move { Ok::<_, std::convert::Infallible>(response) }
                    });
                    if let Err(e) = hyper::server::conn::http1::Builder::new()
                        .timer(hyper_util::rt::TokioTimer::new())
                        .serve_connection(hyper_util::rt::TokioIo::new(stream), service)
                        .await
                    {
                        tracing::debug!("OAuth2 callback connection error: {e}");
                    }
                });
            }
        });
        let params = rx.recv().await.ok_or_else(|| {
            HttpClientError::Default("authorization code not received".to_owned())
        })?;
        Ok((params, server))
    }
}

/// Answer one request of the `OAuth2` callback server: `GET /authorization?...` forwards
/// its query parameters to the waiting login; anything else is a 404.
fn authorization_response(
    req: &http::Request<hyper::body::Incoming>,
    tx: &tokio::sync::mpsc::UnboundedSender<HashMap<String, String>>,
) -> http::Response<http_body_util::Full<bytes::Bytes>> {
    let (status, body) =
        if req.method() != http::Method::GET || req.uri().path() != "/authorization" {
            (StatusCode::NOT_FOUND, "")
        } else if tx
            .send(
                url::form_urlencoded::parse(req.uri().query().unwrap_or_default().as_bytes())
                    .into_owned()
                    .collect(),
            )
            .is_err()
        {
            (
                StatusCode::INTERNAL_SERVER_ERROR,
                "OAuth2 login is no longer waiting for the callback.",
            )
        } else {
            (StatusCode::OK, "You can now close this window.")
        };
    let mut response = http::Response::new(http_body_util::Full::new(bytes::Bytes::from_static(
        body.as_bytes(),
    )));
    *response.status_mut() = status;
    response
}

/// Tokens returned by the Identity Provider token endpoint.
#[derive(Clone)]
pub struct OAuthTokens {
    /// JWT sent to the KMS: the OIDC `id_token` when present (Google and Auth0 put the JWT there), else the `access_token`.
    pub token: String,
    /// Refresh token, returned when `offline_access` is granted, or a rotated one on refresh.
    pub refresh_token: Option<String>,
}

impl std::fmt::Debug for OAuthTokens {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("OAuthTokens(<redacted>)")
    }
}

/// Members of an RFC 6749 token response that the client reads.
#[derive(Deserialize)]
pub(crate) struct OAuthResponse {
    #[serde(rename = "access_token")]
    pub access: String,
    #[serde(rename = "id_token")]
    pub id: Option<String>,
    #[serde(rename = "refresh_token")]
    pub refresh: Option<String>,
}

/// This function requests the tokens from the Identity Provider.
///
/// This function was rewritten because Google returns the JWT token in the
/// `id_token` field, not in the `access_token` field.
///
/// For Google see: <https://developers.google.com/identity/openid-connect/openid-connect#obtainuserinfo>
///
/// # Arguments
///
/// * `login_config` - The `Oauth2LoginConfig` containing the client
///   configuration.
/// * `redirect_url` - The redirect URL used in the `OAuth2` flow.
/// * `pkce_verifier` - The PKCE code verifier used in the `OAuth2` flow.
/// * `authorization_code` - The authorization code received from the Identity
///   Provider.
///
/// # Errors
///
/// This function can return a `HttpClientError` in the following cases:
///
/// * The token exchange request fails.
/// * The token exchange response cannot be parsed.
pub(crate) async fn request_token(
    login_config: &Oauth2LoginConfig,
    redirect_url: &Url,
    pkce_verifier: &str,
    authorization_code: &str,
) -> HttpClientResult<OAuthTokens> {
    let params = [
        ("grant_type", "authorization_code"),
        ("redirect_uri", redirect_url.as_str()),
        ("client_id", login_config.client_id.as_str()),
        ("code", authorization_code),
        ("client_secret", login_config.client_secret.as_str()),
        ("code_verifier", pkce_verifier),
    ];
    token_endpoint_request(&login_config.token_url, &params).await
}

/// Exchange `refresh_token` for new tokens with the `refresh_token` grant (RFC 6749 §6): no browser.
///
/// # Errors
/// Fails if the token endpoint request fails, answers non-200, or returns an unparsable body.
pub async fn refresh_login(
    login_config: &Oauth2LoginConfig,
    refresh_token: &str,
) -> HttpClientResult<OAuthTokens> {
    token_endpoint_request(
        &login_config.token_url,
        &[
            ("grant_type", "refresh_token"),
            ("refresh_token", refresh_token),
            ("client_id", login_config.client_id.as_str()),
            ("client_secret", login_config.client_secret.as_str()),
        ],
    )
    .await
}

/// POST `params` (form-encoded) to the identity provider token endpoint.
async fn token_endpoint_request(
    token_url: &str,
    params: &[(&str, &str)],
) -> HttpClientResult<OAuthTokens> {
    let body = url::form_urlencoded::Serializer::new(String::new())
        .extend_pairs(params)
        .finish();

    // TLS certificate validation MUST remain enabled for the OAuth2 token
    // exchange: the authorization code, PKCE verifier and refresh token are
    // transmitted to the token endpoint, so a MITM with an invalid certificate
    // could steal them.
    let client = super::HttpClient::instantiate(&super::HttpClientConfig {
        server_url: token_url.to_owned(),
        accept_invalid_certs: false,
        ..Default::default()
    })
    .map_err(|e| HttpClientError::Default(format!("failed to create HTTP client: {e}")))?;

    let mut extra_headers = HeaderMap::new();
    extra_headers.append(ACCEPT, HeaderValue::from_static("application/json"));

    let response = client
        .post_form(token_url, &body, &extra_headers)
        .await
        .map_err(|e| {
            HttpClientError::Default(format!("failed issuing token exchange request: {e}"))
        })?;

    if response.status != StatusCode::OK {
        let error_text = response
            .text()
            .unwrap_or_else(|_| "<failed to read response>".to_owned());
        return Err(HttpClientError::Default(format!(
            "failed token exchange: {error_text}"
        )));
    }

    let r: OAuthResponse = response.json().map_err(|e| {
        HttpClientError::Default(format!("failed parsing token exchange response: {e:?}"))
    })?;
    Ok(OAuthTokens {
        // this is where Google returns the JWT token
        token: r.id.unwrap_or(r.access),
        refresh_token: r.refresh,
    })
}

/// Configuration for the Auth Verifier server login.
///
/// Used by the `ckms login cosmian` subcommand.  Set the corresponding
/// `cosmian_conf` section in the KMS client configuration file:
///
/// ```toml
/// [http_config.cosmian_conf]
/// server_url = "https://auth.example.com"
/// realm      = "kms"
/// ```
#[derive(Serialize, Deserialize, Eq, PartialEq, Debug, Clone)]
pub struct AuthVerifierLoginConfig {
    /// Base URL of the Auth Verifier server (no trailing slash).
    pub server_url: String,
    /// Realm to authenticate against (e.g. `"kms"`).
    pub realm: String,
}

/// The next step the authentication server requires after a login attempt.
///
/// Mirrors the server-side `AuthenticationNextStep` enum, serialized as `PascalCase`
/// string variants (e.g. `"TotpRequired"`).
#[derive(Deserialize, Debug, Clone, PartialEq, Eq)]
pub(super) enum AuthenticationNextStep {
    /// Authentication succeeded; the session cookie is set.
    Authenticated,
    /// Server requires a TOTP code before granting the session.
    TotpRequired,
    /// The user's password has expired and must be changed before logging in.
    ChangePassword,
}

/// JSON body returned by the authentication server on every login response.
#[derive(Deserialize, Debug)]
struct AuthenticationResult {
    next_step: AuthenticationNextStep,
}

/// The outcome of a [`auth_verifier_login`] call.
#[derive(Debug)]
pub enum AuthVerifierLoginStep {
    /// Authentication succeeded. Contains the JWT extracted from the `_ea_` cookie.
    Authenticated(String),
    /// The server requires a TOTP code. Re-call [`auth_verifier_login`] with `totp_code: Some(...)`.
    TotpRequired,
}

/// Login to a Auth Verifier server using HTTP Basic credentials.
///
/// Sends `POST {server_url}/login?realm={realm}` with an
/// `Authorization: Basic <base64(username:password)>` header.
///
/// If `totp_code` is `Some`, it is included in the JSON body so that TOTP
/// verification is completed in a single request. Pass `None` on the first
/// call; if the server responds with [`AuthVerifierLoginStep::TotpRequired`],
/// prompt the user and re-call with the code.
///
/// On success the JWT is extracted from the `Set-Cookie: _ea_=<JWT>` header
/// and returned inside [`AuthVerifierLoginStep::Authenticated`]. The caller stores
/// it in `http_config.access_token` and forwards it as a Bearer token on every
/// subsequent KMS request.
///
/// # Errors
///
/// Returns [`HttpClientError`] if the HTTP request fails, the server responds
/// with a non-2xx status, the password has expired, or the `_ea_` cookie is
/// absent from a successful response.
pub async fn auth_verifier_login(
    config: &AuthVerifierLoginConfig,
    username: &str,
    password: &str,
    // TODO: remove accept_invalid_certs
    accept_invalid_certs: bool,
    totp_code: Option<&str>,
) -> HttpClientResult<AuthVerifierLoginStep> {
    /// Name of the session cookie set by the Auth Verifier server.
    const AUTH_VERIFIER_SESSION_COOKIE: &str = "_ea_";

    let mut url = Url::parse(config.server_url.trim_end_matches('/')).map_err(|e| {
        HttpClientError::Default(format!("Invalid Auth Verifier server URL: {e:?}"))
    })?;
    url.path_segments_mut()
        .map_err(|()| {
            HttpClientError::Default(
                "Invalid Auth Verifier server URL: cannot be a base".to_owned(),
            )
        })?
        .push("login");
    url.query_pairs_mut().append_pair("realm", &config.realm);

    let body = totp_code.map_or_else(
        || "{}".to_owned(),
        |code| format!(r#"{{"totp_code":"{code}"}}"#),
    );

    let client = super::HttpClient::instantiate(&super::HttpClientConfig {
        server_url: config.server_url.clone(),
        // TODO: remove accept_invalid_certs
        accept_invalid_certs,
        custom_headers: Some(vec![format!(
            "Authorization: Basic {}",
            BASE64_STANDARD.encode(format!("{username}:{password}"))
        )]),
        ..Default::default()
    })
    .map_err(|e| HttpClientError::Default(format!("failed to create HTTP client: {e}")))?;
    let response = client
        .post_bytes(url.as_str(), body, "application/json")
        .await
        .map_err(|e| HttpClientError::Default(format!("Cosmian login request failed: {e}")))?;

    if !response.status.is_success() {
        let error_text = response
            .text()
            .unwrap_or_else(|_| "<failed to read response>".to_owned());
        return Err(HttpClientError::Default(format!(
            "Cosmian login failed ({}): {error_text}",
            response.status
        )));
    }

    // Parse the JSON body to determine the authentication next step.
    let result: AuthenticationResult = response
        .json()
        .map_err(|e| HttpClientError::Default(format!("Failed to parse login response: {e}")))?;

    match result.next_step {
        AuthenticationNextStep::TotpRequired => return Ok(AuthVerifierLoginStep::TotpRequired),
        AuthenticationNextStep::ChangePassword => {
            return Err(HttpClientError::Default(
                "Your password has expired. Please change it via the Auth Verifier \
                 server before logging in."
                    .to_owned(),
            ));
        }
        AuthenticationNextStep::Authenticated => {}
    }

    // The access token is delivered via `Set-Cookie: _ea_=<JWT>; ...`.
    // There may be multiple Set-Cookie headers; find the first one whose
    // cookie name is exactly `_ea_`.
    for header_value in response.headers().get_all(http::header::SET_COOKIE) {
        let raw = header_value
            .to_str()
            .map_err(|e| HttpClientError::Default(format!("invalid Set-Cookie header: {e}")))?;

        // Each Set-Cookie value has the form:
        //   name=value[; attribute[=value]]*
        // Split at the first ';' to isolate the name=value pair, then split
        // at the first '=' to separate name from value.
        let name_value = raw.split(';').next().unwrap_or(raw);
        if let Some((name, value)) = name_value.split_once('=')
            && name.trim() == AUTH_VERIFIER_SESSION_COOKIE
        {
            return Ok(AuthVerifierLoginStep::Authenticated(
                value.trim().to_owned(),
            ));
        }
    }

    Err(HttpClientError::Default(format!(
        "Cosmian login response did not set the `{AUTH_VERIFIER_SESSION_COOKIE}` session cookie"
    )))
}

/// Request body for the Vault-compatible `AppRole` login endpoint.
///
/// Serialized as `{"role_id": "...", "secret_id": "..."}`. `secret_id` is
/// omitted when the role has `bind_secret_id = false`.
#[derive(Serialize, Debug)]
struct AppRoleLoginRequest<'a> {
    role_id: &'a str,
    #[serde(skip_serializing_if = "Option::is_none")]
    secret_id: Option<&'a str>,
}

/// Response body returned by `POST /v1/auth/approle/login`.
///
/// Mirrors the auth-verifier `AppAuthResponse` wire type; only the
/// `auth.client_token` field is consumed by the client.
#[derive(Deserialize, Debug)]
struct AppRoleLoginResponse {
    auth: AppRoleLoginAuth,
}

/// The `auth` object nested inside [`AppRoleLoginResponse`].
#[derive(Deserialize, Debug)]
struct AppRoleLoginAuth {
    /// The Vault-compatible token to forward as `X-Vault-Token`.
    client_token: String,
}

/// Login to the KMS SPIRE/Vault-compatible API using an `AppRole` identity.
///
/// Sends `POST {server_url}/v1/auth/approle/login` with a JSON body of
/// `{"role_id": ..., "secret_id": ...}`. The KMS transparently proxies this to
/// the configured auth-verifier (`/v1/auth/approle/login`), which validates the
/// credentials and returns a Vault-compatible token.
///
/// The returned `client_token` is stored in `http_config.vault_token` and
/// forwarded as an `X-Vault-Token` header on every subsequent KMS request,
/// where the SPIRE-token middleware validates it against the auth-verifier.
///
/// `secret_id` may be `None` for roles configured with `bind_secret_id = false`.
///
/// The full [`HttpClientConfig`] is used so that the request reuses the same TLS
/// trust store, client certificates, and proxy settings as ordinary KMS calls.
///
/// # Errors
///
/// Returns [`HttpClientError`] if the HTTP client cannot be built, the request
/// fails, the server responds with a non-2xx status, or the response body does
/// not contain an `auth.client_token` field.
pub async fn approle_login(
    http_config: &super::HttpClientConfig,
    role_id: &str,
    secret_id: Option<&str>,
) -> HttpClientResult<String> {
    let client = super::HttpClient::instantiate(http_config)
        .map_err(|e| HttpClientError::Default(format!("failed to create HTTP client: {e}")))?;

    let url = format!(
        "{}/v1/auth/approle/login",
        client.server_url.trim_end_matches('/')
    );

    let response = client
        .post_json(&url, &AppRoleLoginRequest { role_id, secret_id })
        .await
        .map_err(|e| HttpClientError::Default(format!("AppRole login request failed: {e}")))?;

    if response.status != StatusCode::OK {
        let error_text = response
            .text()
            .unwrap_or_else(|_| "<failed to read response>".to_owned());
        return Err(HttpClientError::Default(format!(
            "AppRole login failed ({}): {error_text}",
            response.status
        )));
    }

    let parsed: AppRoleLoginResponse = response.json().map_err(|e| {
        HttpClientError::Default(format!("failed parsing AppRole login response: {e}"))
    })?;

    if parsed.auth.client_token.is_empty() {
        return Err(HttpClientError::Default(
            "AppRole login response contained an empty client_token".to_owned(),
        ));
    }

    Ok(parsed.auth.client_token)
}

#[cfg(test)]
mod oauth_response_tests {
    use super::OAuthResponse;

    /// A standard RFC 6749 token response carries more members than the client reads
    /// (`expires_in`, `scope`, `token_type`); they must be accepted and ignored.
    #[test]
    fn full_rfc6749_token_response_is_accepted() {
        let response = serde_json::from_str::<OAuthResponse>(
            r#"{
                "access_token": "at",
                "id_token": "it",
                "expires_in": 3600,
                "refresh_token": "rt",
                "scope": "openid email",
                "token_type": "Bearer"
            }"#,
        )
        .ok();
        assert_eq!(response.as_ref().map(|r| r.access.as_str()), Some("at"));
        assert_eq!(
            response.as_ref().and_then(|r| r.refresh.as_deref()),
            Some("rt")
        );
        assert_eq!(response.and_then(|r| r.id).as_deref(), Some("it"));
    }

    #[test]
    fn id_token_is_optional() {
        let response = serde_json::from_str::<OAuthResponse>(
            r#"{"access_token": "at", "token_type": "Bearer"}"#,
        )
        .ok();
        assert_eq!(response.as_ref().map(|r| r.access.as_str()), Some("at"));
        assert_eq!(response.map(|r| r.id), Some(None));
    }

    #[test]
    fn access_token_is_required() {
        let response = serde_json::from_str::<OAuthResponse>(r#"{"id_token": "it"}"#).ok();
        assert!(response.is_none());
    }
}

#[cfg(test)]
mod characterization_tests {
    //! Characterization tests for the `OAuth2` callback server of `LoginState`.

    use std::{
        collections::HashMap,
        io::{Read, Write},
        net::TcpStream,
        sync::mpsc,
        thread,
        time::Duration,
    };

    use super::LoginState;

    /// Send a raw HTTP GET to the callback server and return the full raw response.
    fn browser_get(port: u16, path_query: &str, tx: mpsc::Sender<String>) {
        let path_query = path_query.to_owned();
        thread::spawn(move || {
            thread::sleep(Duration::from_millis(50));
            let mut stream = TcpStream::connect(("127.0.0.1", port)).unwrap();
            let request = format!(
                "GET {path_query} HTTP/1.1\r\nHost: 127.0.0.1:{port}\r\nConnection: close\r\n\r\n"
            );
            stream.write_all(request.as_bytes()).unwrap();
            let mut response = String::new();
            stream.read_to_string(&mut response).unwrap();
            tx.send(response).unwrap();
        });
    }

    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    async fn characterization_receive_authorization_parameters_returns_query_and_ok_page() {
        const PORT: u16 = 17_951;
        let (tx, rx) = mpsc::channel();
        browser_get(PORT, "/authorization?code=abc%20def&state=xyz&extra=", tx);

        let (params, handle) = LoginState::receive_authorization_parameters(PORT)
            .await
            .unwrap();

        let expected: HashMap<String, String> = HashMap::from([
            ("code".to_owned(), "abc def".to_owned()),
            ("state".to_owned(), "xyz".to_owned()),
            ("extra".to_owned(), String::new()),
        ]);
        assert_eq!(params, expected);

        let response = rx.recv_timeout(Duration::from_secs(10)).unwrap();
        assert!(response.starts_with("HTTP/1.1 200 OK\r\n"), "{response}");
        assert!(
            response.ends_with("You can now close this window."),
            "{response}"
        );
        handle.abort();
    }

    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    async fn characterization_receive_authorization_parameters_port_in_use() {
        const PORT: u16 = 17_952;
        let _listener = std::net::TcpListener::bind(("127.0.0.1", PORT)).unwrap();
        let err = LoginState::receive_authorization_parameters(PORT)
            .await
            .unwrap_err();
        assert!(
            err.to_string()
                .contains("cannot bind port 17952 for OAuth2 callback: "),
            "{err}"
        );
    }

    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    async fn characterization_callback_after_login_returned_gets_500() {
        const PORT: u16 = 17_953;
        let (tx, rx) = mpsc::channel();
        browser_get(PORT, "/authorization?code=first", tx);
        // The receiver is dropped when this returns; the server keeps running until `handle` aborts it.
        let (_params, handle) = LoginState::receive_authorization_parameters(PORT)
            .await
            .unwrap();
        rx.recv_timeout(Duration::from_secs(10)).unwrap();

        let (tx, rx) = mpsc::channel();
        browser_get(PORT, "/authorization?code=second", tx);
        let response = rx.recv_timeout(Duration::from_secs(10)).unwrap();
        assert!(
            response.starts_with("HTTP/1.1 500 Internal Server Error\r\n"),
            "{response}"
        );
        assert!(
            response.ends_with("OAuth2 login is no longer waiting for the callback."),
            "{response}"
        );
        handle.abort();
    }
}

#[cfg(test)]
mod pkce_tests {
    use std::collections::HashMap;

    use url::Url;

    use super::{
        LoginState, Oauth2LoginConfig, authorization_url, constant_time_eq, pkce_challenge,
        random_token,
    };

    fn config(authorize_url: &str, scopes: &[&str]) -> Oauth2LoginConfig {
        Oauth2LoginConfig {
            client_id: "my client&id".to_owned(),
            client_secret: "secret".to_owned(),
            authorize_url: authorize_url.to_owned(),
            token_url: "https://idp.example.com/token".to_owned(),
            scopes: scopes.iter().map(|s| (*s).to_owned()).collect(),
            refresh_token: None,
        }
    }

    /// RFC 7636 appendix B test vector.
    #[test]
    fn pkce_challenge_matches_rfc7636_appendix_b() {
        assert_eq!(
            pkce_challenge("dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk").unwrap(),
            "E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM"
        );
    }

    #[test]
    fn random_token_is_unpadded_base64url_of_requested_entropy() {
        let token = random_token(32).unwrap();
        assert_eq!(token.len(), 43);
        assert!(
            token
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_'),
            "{}",
            token.as_str()
        );
    }

    #[test]
    fn state_and_verifier_differ_between_logins() {
        let cfg = config("https://idp.example.com/auth", &[]);
        let a = LoginState::try_from_with_port(cfg.clone(), 17_954).unwrap();
        let b = LoginState::try_from_with_port(cfg, 17_954).unwrap();
        assert_ne!(*a.csrf_token, *b.csrf_token);
        assert_ne!(*a.pkce_verifier, *b.pkce_verifier);
        assert_ne!(*a.csrf_token, *a.pkce_verifier);
        assert_ne!(a.auth_url, b.auth_url);
    }

    #[test]
    fn authorization_url_contains_all_parameters() {
        let redirect = Url::parse("http://localhost:17899/authorization").unwrap();
        let url = authorization_url(
            &config(
                "https://idp.example.com/auth?prompt=consent",
                &["openid", "email"],
            ),
            &redirect,
            "st",
            "ch",
        )
        .unwrap();
        let pairs: Vec<(String, String)> = url.query_pairs().into_owned().collect();
        let expected = [
            ("prompt", "consent"),
            ("response_type", "code"),
            ("client_id", "my client&id"),
            ("redirect_uri", "http://localhost:17899/authorization"),
            ("state", "st"),
            ("code_challenge", "ch"),
            ("code_challenge_method", "S256"),
            ("scope", "openid email"),
        ]
        .map(|(k, v)| (k.to_owned(), v.to_owned()));
        assert_eq!(pairs, expected);
        let query = url.query().unwrap();
        assert!(
            query.contains("redirect_uri=http%3A%2F%2Flocalhost%3A17899%2Fauthorization"),
            "{query}"
        );
        assert!(query.contains("client_id=my+client%26id"), "{query}");
        assert!(query.ends_with("scope=openid+email"), "{query}");
        assert_eq!(url.host_str(), Some("idp.example.com"));
        assert_eq!(url.path(), "/auth");
    }

    #[test]
    fn authorization_url_without_scopes_has_no_scope_parameter() {
        let redirect = Url::parse("http://localhost:17899/authorization").unwrap();
        let url = authorization_url(
            &config("https://idp.example.com/auth", &[]),
            &redirect,
            "st",
            "ch",
        )
        .unwrap();
        let pairs: HashMap<String, String> = url.query_pairs().into_owned().collect();
        assert!(!pairs.contains_key("scope"));
        assert_eq!(pairs.len(), 6);
    }

    #[test]
    fn invalid_urls_are_rejected() {
        let redirect = Url::parse("http://localhost:17899/authorization").unwrap();
        drop(authorization_url(&config("not a url", &[]), &redirect, "s", "c").unwrap_err());
        let mut cfg = config("https://idp.example.com/auth", &[]);
        cfg.token_url = "not a url".to_owned();
        drop(
            LoginState::try_from_with_port(cfg, 17_955)
                .map(|_| ())
                .unwrap_err(),
        );
    }

    #[test]
    fn constant_time_eq_compares_content_and_length() {
        assert!(constant_time_eq("abc", "abc"));
        assert!(!constant_time_eq("abc", "and"));
        assert!(!constant_time_eq("abc", "abcd"));
    }
}
