//! The only place where the XML vector harness may accept a difference from a vector.
//!
//! `DEVIATIONS` lists single checks of single batch items that deviate by design;
//! `REASON_DEVIATIONS` lists exact Result Reason pairs at enumerated batch items;
//! `KNOWN_FAILING` lists whole vectors that must currently fail. Both are asserted:
//! a `KNOWN_FAILING` vector that starts passing fails the suite, and every stem in
//! either table must name an existing vector file.

use std::{
    collections::{BTreeSet, HashSet},
    sync::Mutex,
};

use cosmian_kmip::kmip_0::kmip_types::ErrorReason;
use cosmian_logger::warn;

/// Position of a batch item in a vector run, used to look up deviations.
#[derive(Clone, Copy)]
pub(crate) struct Ctx<'a> {
    pub vector: &'a str,
    pub request: usize,
    pub batch: usize,
    /// UIDs of the objects the server generated (`Create`, `CreateKeyPair`, ...) in this run.
    pub generated_uids: &'a HashSet<String>,
    /// The object being compared was generated by the server: its key bytes, digest and
    /// original creation date are fresh server material, so the vector's literals (recorded
    /// on the reference server) cannot match; their presence and length still must.
    pub object_generated: bool,
}

/// One accepted deviation: `check` of batch item `batch` of response `request` of `vector`.
pub(crate) struct Deviation {
    pub vector: &'static str,
    pub request: usize,
    pub batch: usize,
    pub check: &'static str,
    pub reason: &'static str,
}

/// A deviation of batch item 0.
const fn dev(
    vector: &'static str,
    request: usize,
    check: &'static str,
    reason: &'static str,
) -> Deviation {
    Deviation {
        vector,
        request,
        batch: 0,
        check,
        reason,
    }
}

/// One accepted Result Reason difference: where the vector expects `expected`, the server
/// answers `actual`, at exactly the listed (vector, request, batch) `positions`. 1.x reasons
/// are matched through their 2.x equivalent (same KMIP code). Every position is asserted used.
pub(crate) struct ReasonDeviation {
    pub expected: ErrorReason,
    pub actual: ErrorReason,
    pub positions: &'static [(&'static str, usize, usize)],
    pub reason: &'static str,
}

