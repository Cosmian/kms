/// Attributes the server does not implement, as KMIP 2.1 tag names (1.x attribute names
/// match with spaces removed). The one systematic deviation: wherever a vector expects one of
/// them, it may be missing from Get Attribute List and Get Attributes responses.
pub(crate) const UNIMPLEMENTED_ATTRIBUTES: &[&str] = &["LeaseTime", "ProtectionStorageMask"];

/// Whether `name` (2.1 tag name or 1.x attribute name) is in `UNIMPLEMENTED_ATTRIBUTES`.
pub(crate) fn is_unimplemented_attribute(name: &str) -> bool {
    let name: String = name.split_whitespace().collect();
    UNIMPLEMENTED_ATTRIBUTES.contains(&name.as_str())
}

