/// Indexes of the `DEVIATIONS` rows used since the last `take_unused_deviations`.
static USED: Mutex<BTreeSet<usize>> = Mutex::new(BTreeSet::new());
/// (row, position) indexes of the `REASON_DEVIATIONS` positions used since the last
/// `take_unused_deviations`.
static USED_REASONS: Mutex<BTreeSet<(usize, usize)>> = Mutex::new(BTreeSet::new());

/// The `DEVIATIONS` rows and `REASON_DEVIATIONS` positions of `vector` not used since the
/// previous call; resets the record.
pub(crate) fn take_unused_deviations(vector: &str) -> Vec<String> {
    let mut used = USED
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    let mut unused: Vec<String> = DEVIATIONS
        .iter()
        .enumerate()
        .filter(|(i, d)| d.vector == vector && !used.contains(i))
        .map(|(_, d)| format!("request[{}] batch[{}] `{}`", d.request, d.batch, d.check))
        .collect();
    used.clear();
    let mut used_reasons = USED_REASONS
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    for (row, d) in REASON_DEVIATIONS.iter().enumerate() {
        for (pos, (stem, request, batch)) in d.positions.iter().enumerate() {
            if *stem == vector && !used_reasons.contains(&(row, pos)) {
                unused.push(format!(
                    "request[{request}] batch[{batch}] `result_reason` {:?} -> {:?}",
                    d.expected, d.actual
                ));
            }
        }
    }
    used_reasons.clear();
    unused
}

impl Ctx<'_> {
    /// True when `check` is an accepted deviation for this batch item; logs it with `warn!`.
    pub(crate) fn allows(&self, check: &str) -> bool {
        DEVIATIONS
            .iter()
            .enumerate()
            .find(|(_, d)| {
                d.vector == self.vector
                    && d.request == self.request
                    && d.batch == self.batch
                    && d.check == check
            })
            .is_some_and(|(i, d)| {
                USED.lock()
                    .unwrap_or_else(std::sync::PoisonError::into_inner)
                    .insert(i);
                warn!(
                    "{} request[{}] batch[{}]: accepted deviation `{check}`: {}",
                    self.vector, self.request, self.batch, d.reason
                );
                true
            })
    }

    /// True when the vector's `expected` Result Reason answered as `actual` is an accepted
    /// `REASON_DEVIATIONS` pair at this batch item; logs it with `warn!`.
    pub(crate) fn allows_reason(&self, expected: ErrorReason, actual: ErrorReason) -> bool {
        let here = (self.vector, self.request, self.batch);
        REASON_DEVIATIONS
            .iter()
            .enumerate()
            .filter(|(_, d)| d.expected == expected && d.actual == actual)
            .find_map(|(row, d)| {
                let pos = d.positions.iter().position(|p| *p == here)?;
                Some((row, pos, d))
            })
            .is_some_and(|(row, pos, d)| {
                USED_REASONS
                    .lock()
                    .unwrap_or_else(std::sync::PoisonError::into_inner)
                    .insert((row, pos));
                warn!(
                    "{} request[{}] batch[{}]: accepted result_reason {expected:?} -> \
                     {actual:?}: {}",
                    self.vector, self.request, self.batch, d.reason
                );
                true
            })
    }

    /// This context for comparing the object identified by `uid`.
    pub(crate) fn for_object(&self, uid: &str) -> Self {
        Self {
            object_generated: self.generated_uids.contains(uid),
            ..*self
        }
    }
}
